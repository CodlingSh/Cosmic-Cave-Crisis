class Title {
  private:
    uint8_t x = 22;
    uint8_t y = 2;
    int16_t groundOffset = 0;
    uint8_t groundSpeed = 6;

  public:
    void draw() {
      // COSMIC
      Sprites::drawOverwrite(x, y, c, 0);
      Sprites::drawOverwrite(x+14, y, o, 0);
      Sprites::drawOverwrite(x+28, y, s, 0);
      Sprites::drawOverwrite(x+42, y, m, 0);
      Sprites::drawOverwrite(x+60, y, i, 0);
      Sprites::drawOverwrite(x+72, y, c, 0);
      // CAVERN
      Sprites::drawOverwrite(x+1, y+15, c, 0);
      Sprites::drawOverwrite(x+15, y+15, a, 0);
      Sprites::drawOverwrite(x+29, y+15, v, 0);
      Sprites::drawOverwrite(x+43, y+15, e, 0);
      Sprites::drawOverwrite(x+57, y+15, r, 0);
      Sprites::drawOverwrite(x+71, y+15, n, 0);
      // CRISIS
      Sprites::drawOverwrite(x+3, y+30, c, 0);
      Sprites::drawOverwrite(x+17, y+30, r, 0);
      Sprites::drawOverwrite(x+31, y+30, i, 0);
      Sprites::drawOverwrite(x+43, y+30, s, 0);
      Sprites::drawOverwrite(x+57, y+30, i, 0);
      Sprites::drawOverwrite(x+69, y+30, s, 0);
      // GROUND
      Sprites::drawOverwrite(0-(groundOffset/groundSpeed), 52, moonGround, 0);
      Sprites::drawOverwrite(178-(groundOffset/groundSpeed), 52, moonGround, 0);
    }

    void update() {
      groundOffset++;

      if (groundOffset >= (178*groundSpeed)) {
        groundOffset = 0;
      }
    }
};

